from typing import Any
from PySide6.QtCore import Qt, QTimer
from PySide6.QtWidgets import (QWidget, QFrame, QLabel, QPushButton, QVBoxLayout, QHBoxLayout,
    QListWidget, QLineEdit, QTextEdit, QSplitter, QScrollArea)
from ..components import GlassPanel
from ..components.icons import svg_icon


def build_chats(self):
    page, layout = self._page("گفتگوها", "گفتگوهای بله را جست‌وجو کن، تاریخچه را ببین و پاسخ‌ها را مدیریت کن.")
    tools = QHBoxLayout(); tools.setSpacing(9)
    self.chat_search = QLineEdit()
    self.chat_search.setPlaceholderText("جست‌وجو در مخاطبان و گفتگوهای بارگذاری‌شده…")
    self.chat_search.textChanged.connect(self.filter_chats)
    tools.addWidget(self.chat_search, 1)
    load = QPushButton("بارگذاری گفتگوها"); load.setObjectName("Primary")
    load.clicked.connect(self.load_dialogs)
    tools.addWidget(load)
    layout.addLayout(tools)

    splitter = QSplitter(Qt.Horizontal)
    splitter.setObjectName("ChatSplitter")
    splitter.setChildrenCollapsible(False)
    splitter.setHandleWidth(7)
    splitter.setLayoutDirection(Qt.RightToLeft)

    list_panel, lp = self._panel("فهرست گفتگوها")
    self.chat_list = QListWidget()
    self.chat_list.setObjectName("chat_list")
    self.chat_list.setSpacing(3)
    self.chat_list.itemSelectionChanged.connect(self.on_chat_selected)
    lp.addWidget(self.chat_list, 1)
    self.chat_count_label = QLabel("برای نمایش گفتگوها، فهرست را بارگذاری کن.")
    self.chat_count_label.setObjectName("Muted")
    lp.addWidget(self.chat_count_label)
    list_panel.setMinimumWidth(270)
    list_panel.setMaximumWidth(390)
    splitter.addWidget(list_panel)

    conversation_panel = GlassPanel(radius=22, variant="material", interactive=False)
    conversation_panel.setObjectName("ConversationSurface")
    right = QVBoxLayout(conversation_panel)
    right.setContentsMargins(17, 15, 17, 15); right.setSpacing(11)

    header = QHBoxLayout()
    heading_col = QVBoxLayout(); heading_col.setSpacing(2)
    self.chat_heading = QLabel("یک گفتگو را انتخاب کن")
    self.chat_heading.setObjectName("SectionTitle")
    self.chat_heading.setStyleSheet("font-size:12pt;")
    heading_col.addWidget(self.chat_heading)
    self.chat_meta = QLabel("پیام‌های گفتگو پس از انتخاب در این قسمت نمایش داده می‌شوند.")
    self.chat_meta.setObjectName("Muted"); self.chat_meta.setStyleSheet("font-size:8.5pt;")
    heading_col.addWidget(self.chat_meta)
    header.addLayout(heading_col, 1)
    self.message_search = QLineEdit()
    self.message_search.setPlaceholderText("جست‌وجو در پیام‌ها…")
    self.message_search.setMaximumWidth(240)
    self.message_search.textChanged.connect(self.filter_messages)
    header.addWidget(self.message_search)
    export_btn = QPushButton("خروجی")
    export_btn.clicked.connect(self.export_chat_history)
    header.addWidget(export_btn)
    reload_btn = QPushButton("تازه‌سازی")
    reload_btn.clicked.connect(self.load_history)
    header.addWidget(reload_btn)
    right.addLayout(header)

    self.message_scroll = QScrollArea()
    self.message_scroll.setObjectName("MessageScroll")
    self.message_scroll.setWidgetResizable(True)
    self.message_scroll.setFrameShape(QFrame.NoFrame)
    self.message_scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    self.message_container = QWidget()
    self.message_container.setObjectName("MessageContainer")
    self.message_container.setAttribute(Qt.WA_TranslucentBackground, True)
    self.message_layout = QVBoxLayout(self.message_container)
    self.message_layout.setContentsMargins(8, 8, 8, 8)
    self.message_layout.setSpacing(8)
    self.message_scroll.setWidget(self.message_container)
    right.addWidget(self.message_scroll, 1)

    composer = GlassPanel(radius=17, variant="material", interactive=False)
    composer_layout = QVBoxLayout(composer)
    composer_layout.setContentsMargins(12, 10, 12, 10); composer_layout.setSpacing(8)
    self.message_input = QTextEdit()
    self.message_input.setObjectName("message_input")
    self.message_input.setPlaceholderText("پیامت را اینجا بنویس…")
    self.message_input.setFixedHeight(76)
    composer_layout.addWidget(self.message_input)
    action_row = QHBoxLayout(); action_row.setSpacing(7)
    send = QPushButton("ارسال پیام"); send.setObjectName("Primary")
    send.clicked.connect(self.send_chat_message)
    file_btn = QPushButton("ارسال فایل"); file_btn.clicked.connect(self.send_chat_file)
    ai_btn = QPushButton("پیشنهاد AI"); ai_btn.clicked.connect(self.draft_chat_reply)
    schedule_btn = QPushButton("زمان‌بندی"); schedule_btn.clicked.connect(self.schedule_chat_message)
    action_row.addWidget(send); action_row.addWidget(file_btn); action_row.addWidget(ai_btn); action_row.addWidget(schedule_btn)
    action_row.addStretch(1)
    hint = QLabel("Enter برای خط جدید  ·  ارسال فقط پس از بررسی مقصد و متن")
    hint.setObjectName("Muted"); hint.setStyleSheet("font-size:8pt;")
    action_row.addWidget(hint)
    composer_layout.addLayout(action_row)
    right.addWidget(composer)
    splitter.addWidget(conversation_panel)
    splitter.setSizes([320, 920])
    layout.addWidget(splitter, 1)
    self.render_messages([])
    return page


def render_messages(self, rows: list[dict[str, Any]]):
    """Render message bubbles using the new surface primitives."""
    from PySide6.QtWidgets import QHBoxLayout
    # GlassPanel is imported at module scope from ui.components.
    self.current_messages = list(rows)
    self.message_row_widgets = []
    while self.message_layout.count():
        item = self.message_layout.takeAt(0)
        widget = item.widget()
        if widget:
            widget.deleteLater()

    if not rows:
        empty = GlassPanel(radius=20, variant="material", interactive=False)
        empty.setMaximumWidth(510)
        empty.setMinimumWidth(260)
        el = QVBoxLayout(empty); el.setContentsMargins(25, 23, 25, 23); el.setSpacing(9)
        icon = QLabel(); icon.setAlignment(Qt.AlignCenter)
        icon.setPixmap(svg_icon("chats", "#A7A9E8" if not self.dark_mode else "#C2C7FF").pixmap(42, 42))
        el.addWidget(icon)
        title = QLabel("هنوز پیامی برای نمایش وجود ندارد")
        title.setObjectName("SectionTitle"); title.setAlignment(Qt.AlignCenter)
        detail = QLabel("از فهرست سمت راست یک گفتگو انتخاب کن. اگر فهرست خالی است، ابتدا گفتگوها را بارگذاری کن.")
        detail.setObjectName("Muted"); detail.setAlignment(Qt.AlignCenter); detail.setWordWrap(True)
        el.addWidget(title); el.addWidget(detail)
        self.message_layout.addStretch(1)
        self.message_layout.addWidget(empty, alignment=Qt.AlignCenter)
        self.message_layout.addStretch(1)
        if hasattr(self, "message_search"):
            self.filter_messages(self.message_search.text())
        return

    for message in rows:
        bubble = GlassPanel(radius=17, variant="message_out" if message.get("out") else "message_in", interactive=True)
        bubble.setObjectName("MessageOut" if message.get("out") else "MessageIn")
        bubble.setMaximumWidth(680)
        bubble.setProperty("guide_title", "پیام ارسالی" if message.get("out") else "پیام دریافتی")
        bubble.setProperty("guide_topic", "chats")
        bubble.setProperty("guide_body", "برای عملیات روی پیام، راست‌کلیک کن. متن پیام قابل انتخاب و کپی است.")
        bubble.setContextMenuPolicy(Qt.CustomContextMenu)
        bubble.customContextMenuRequested.connect(lambda pos, m=message, b=bubble: self.show_message_menu(m, b.mapToGlobal(pos)))
        bl = QVBoxLayout(bubble); bl.setContentsMargins(14, 10, 14, 9); bl.setSpacing(6)
        text = QLabel(str(message.get("text", "")))
        text.setWordWrap(True); text.setTextInteractionFlags(Qt.TextSelectableByMouse)
        text.setContextMenuPolicy(Qt.CustomContextMenu)
        text.customContextMenuRequested.connect(lambda pos, m=message, w=text: self.show_message_menu(m, w.mapToGlobal(pos)))
        stamp = QLabel(("شما" if message.get("out") else "مخاطب") + "  ·  " + str(message.get("date", "")) + "  ·  #" + str(message.get("id", "")))
        stamp.setObjectName("Muted"); stamp.setStyleSheet("font-size:8pt;")
        bl.addWidget(text); bl.addWidget(stamp)
        row_widget = QWidget(); row = QHBoxLayout(row_widget); row.setContentsMargins(2, 1, 2, 1)
        row.setDirection(QHBoxLayout.LeftToRight)
        if message.get("out"):
            row.addStretch(1); row.addWidget(bubble)
        else:
            row.addWidget(bubble); row.addStretch(1)
        self.message_layout.addWidget(row_widget)
        self.message_row_widgets.append((row_widget, message))
    self.message_layout.addStretch(1)
    self.filter_messages(self.message_search.text())
    QTimer.singleShot(0, lambda: self.message_scroll.verticalScrollBar().setValue(self.message_scroll.verticalScrollBar().maximum()))
